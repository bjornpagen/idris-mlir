#include "idr/Transforms/Expect.h"

#include "llvm/ADT/StringSwitch.h"

namespace idr::expect {

Check lookup(llvm::StringRef name) {
  return llvm::StringSwitch<Check>(name)
      .Case("no-closures", noClosures)
      .Case("no-heap-allocation", noHeapAllocation)
      .Case("one-clone", oneClone)
      .Case("not-called", notCalled)
      .Case("quantities-kept", quantitiesKept)
      .Case("reuses-in-place", reusesInPlace)
      .Case("moves-out", movesOut)
      .Case("counts-nothing", countsNothing)
      .Case("no-guards", noGuards)
      .Case("tests-nothing", testsNothing)
      .Case("resets-unshared", resetsUnshared)
      .Case("reuses-every-cell", reusesEveryCell)
      .Case("contified", contified)
      .Case("facts-as-marked", factsAsMarked)
      .Case("output-fused", outputFused)
      .Case("folds-balanced", foldsBalanced)
      .Case("constant-stack", constantStack)
      .Case("counted-loop", countedLoop)
      .Case("word-loop", wordLoop)
      .Case("structured-loops", structuredLoops)
      .Case("typed-reads", typedReads)
      .Case("in-place", inPlace)
      .Case("fused", fused)
      .Case("largest-function", largestFunction)
      .Case("vectorized", vectorized)
      .Case("narrowed-lanes", narrowedLanes)
      .Case("matches", matches)
      .Case("matches-nothing", matchesNothing)
      .Case("forces", forcesSome)
      .Case("forces-nothing", forcesNothing)
      .Case("builds", buildsSome)
      .Case("builds-nothing", buildsNothing)
      .Case("reads-fields", readsFields)
      .Case("reads-no-fields", readsNoFields)
      .Case("applies", applies)
      .Case("never-returns", neverReturns)
      .Case("calls", calls)
      .Case("never-calls", neverCalls)
      .Case("calls-closed", callsClosed)
      .Case("returns", returnsConstants)
      .Case("returns-argument", returnsArguments)
      .Case("returns-on-paths", returnsOnPaths)
      .Case("builds-where-used", buildsWhereUsed)
      .Case("matches-once", matchesOnce)
      .Case("crashes-before-output", crashesBeforeOutput)
      .Case("parameters-used", parametersUsed)
      .Case("results-used", resultsUsed)
      .Case("regions-distinct", regionsDistinct)
      .Case("checks-every-path", checksEveryPath)
      .Case("grows-nothing", growsNothing)
      .Case("call-order", callOrder)
      .Case("calls-only", callsOnly)
      .Case("direct-calls", directCalls)
      .Case("crash-sites", crashSites)
      .Case("lowered", lowered)
      .Case("in-llvm", inLLVM)
      .Case("signature", signature)
      .Case("entry", entry)
      .Case("linker-names", linkerNames)
      .Case("loops", loops)
      .Case("straight-line", straightLine)
      .Case("aligned-access", alignedAccess)
      .Case("reads-nothing", readsNothing)
      .Case("writes-nothing", writesNothing)
      .Case("effects", solvedEffects)
      .Case("computes-nothing", computesNothing)
      .Case("dims-known", dimsKnown)
      .Case("by-name", byName)
      .Case("not-by-name", notByName)
      .Case("total", total)
      .Case("not-total", notTotal)
      .Case("apart", apart)
      .Case("reaches", reaches)
      .Case("stage", stage)
      .Default(nullptr);
}

} // namespace idr::expect
