# Assembles each lane's dispatch from parts/, so the shared text is written
# once: the owner's representation-first guideline first, so that it is read
# before anything else, then the lane's body, then the common obligations,
# then the six binding rules, all verbatim. dispatch/ is output; edit parts/
# instead.
import json
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
# Where the lane's own text starts, for validate.py.
LANE = "<!-- lane -->"


HEAD = "<!-- SPDX-License-Identifier: 0BSD -->\n<!-- Copyright (c) 2026 Bjorn Pagen -->\n"


def body(text):
    """A part's text without its licence lines, which the dispatch carries once."""
    lines = text.split("\n")
    while lines and (lines[0].startswith("<!-- SPDX-License-Identifier:") or lines[0].startswith("<!-- Copyright")):
        lines.pop(0)
    return "\n".join(lines).rstrip("\n") + "\n"


def read(*path):
    with open(os.path.join(here, *path), encoding="utf-8") as f:
        return body(f.read())


def main():
    owners = json.load(open(os.path.join(here, "ownership.json"), encoding="utf-8"))
    common = read("parts", "common.md")
    rules = read("parts", "rules.md")
    representation = read("parts", "representation.md")
    os.makedirs(os.path.join(here, "dispatch"), exist_ok=True)
    missing = []
    for lane in owners:
        if lane == "coordinator":
            continue
        body_path = os.path.join(here, "parts", "lanes", lane + ".md")
        if not os.path.exists(body_path):
            missing.append(lane)
            continue
        body = read("parts", "lanes", lane + ".md")
        header = HEAD + (
            f"<!-- Generated by proposals/0014-sound/assemble.py from parts/representation.md, "
            f"parts/lanes/{lane}.md, parts/common.md and parts/rules.md; edit those. -->\n"
            f"# Dispatch: lane {lane} of proposal 0014\n\n"
            "This file is your whole assignment. The packet it quotes is "
            "`proposals/0014-sound/README.md`. Read the owner's guideline below in "
            "full before anything else: every hunk you write is judged by it.\n\n"
        )
        with open(os.path.join(here, "dispatch", lane + ".md"), "w", encoding="utf-8") as f:
            f.write(header + representation + "\n" + LANE + "\n" + body + "\n" + common + "\n" + rules)
    if missing:
        print("no lane body for: " + ", ".join(missing))
        return 1
    print("assembled " + str(len(owners) - 1) + " dispatches")
    return 0


if __name__ == "__main__":
    sys.exit(main())
